const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('islandAPI', {
  onMedia: (cb) => ipcRenderer.on('media', (_e, d) => cb(d)),
  onClaude: (cb) => ipcRenderer.on('claude', (_e, d) => cb(d)),
  mediaControl: (action) => ipcRenderer.send('media-control', action),
  getBlurConfig: () => ipcRenderer.invoke('blur-config'),
  onBlurChanged: (cb) => ipcRenderer.on('blur-changed', () => cb()),
  onAudio: (cb) => ipcRenderer.on('audio', (_e, d) => cb(d)),
  getAudio: () => ipcRenderer.invoke('audio-get'),
  audioCommand: (cmd, value) => ipcRenderer.send('audio-command', cmd, value),
  quickAction: (name) => ipcRenderer.send('quick-action', name),
  onFavorites: (cb) => ipcRenderer.on('favorites', (_e, list) => cb(list)),
  getFavorites: () => ipcRenderer.invoke('favorites-get'),
  listApps: (force) => ipcRenderer.invoke('apps-list', force),
  addFavoriteApp: (id) => ipcRenderer.invoke('favorites-add-app', id),
  addFavorite: (kind) => ipcRenderer.invoke('favorites-add', kind),
  removeFavorite: (index) => ipcRenderer.send('favorites-remove', index),
  openFavorite: (index) => ipcRenderer.send('favorite-open', index),
  onUpdateReady: (cb) => ipcRenderer.on('update-ready', (_e, v) => cb(v)),
  openSettings: (section) => ipcRenderer.send('open-settings', section),
  onUsage: (cb) => ipcRenderer.on('usage', (_e, u) => cb(u)),
  getUsage: () => ipcRenderer.invoke('usage-get'),
  setClaudeUsage: (on) => ipcRenderer.invoke('claude-usage-set', on),
  getUpdate: () => ipcRenderer.invoke('update-get'),
  checkUpdate: () => ipcRenderer.send('update-check'),
  installUpdate: () => ipcRenderer.send('update-install'),
  onUpdateStatus: (cb) => ipcRenderer.on('update-status', (_e, s) => cb(s)),
  onLibrary: (cb) => ipcRenderer.on('library', (_e, l) => cb(l)),
  getLibrary: () => ipcRenderer.invoke('library-get'),
  refreshLibrary: () => ipcRenderer.invoke('library-refresh'),
  openLibrary: (id) => ipcRenderer.send('library-open', id),
  hideLibrary: (id, hide) => ipcRenderer.send('library-hide', id, hide),
  addLibrary: (kind, appId) => ipcRenderer.invoke('library-add', kind, appId),
  removeLibrary: (id) => ipcRenderer.send('library-remove', id),
  getOfficeRecents: (kind) => ipcRenderer.invoke('office-recents', kind),
  openOfficeRecent: (id) => ipcRenderer.send('office-open-recent', id),
  onFocusSection: (cb) => ipcRenderer.on('focus-section', (_e, s) => cb(s)),
  getClaudeLink: () => ipcRenderer.invoke('claude-link-status'),
  setClaudeLink: (link) => ipcRenderer.invoke('claude-link-set', link),
  onClaudeLink: (cb) => ipcRenderer.on('claude-link', (_e, s) => cb(s)),
  getSettings: () => ipcRenderer.invoke('settings-get'),
  setSettings: (patch) => ipcRenderer.send('settings-set', patch),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  setInteractive: (on) => ipcRenderer.send('set-interactive', on),
});
